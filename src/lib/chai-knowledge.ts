export const COFFEE_STORY = `
**India's coffee**
India has grown coffee since the 1600s, when a Sufi saint, Baba Budan, is said
to have carried seven beans home from Yemen. Today India grows distinctive
shade-grown arabica. Three ways it reaches the cup:
  - Filter coffee, South India: brewed slow through a metal filter, served
    frothy in a steel tumbler. Robust and ritualistic.
  - Espresso and lattes, the modern cafe: the Italian method reimagined with
    Indian flavours like jaggery, cardamom and pistachio.
  - Cold brew: steeped slow over many hours. Smooth, low-acid, naturally sweet.
Our beans are the exclusive Sula Blend, roasted locally by Alai Coffee from
Chikmagalur and Odisha origins.
`.trim();

export const HOME_RECIPE = `
**Classic masala chai at home** (shares this only if a customer asks how to
make chai. 15 minutes, serves 2.)
Ingredients: 2 cups water, 1 cup whole milk, 2 tsp loose Assam tea, 4 green
cardamom pods crushed, 1 inch fresh ginger sliced, 2 whole cloves, 1 small
cinnamon stick, 2 to 3 black peppercorns, 2 to 3 tsp sugar or jaggery.
Method: crush the spices lightly to release the oils. Boil the water with the
spices and simmer 3 to 4 minutes. Add the tea, simmer 2 more minutes. Add the
milk, bring to a gentle boil, watch it closely. Add sugar or jaggery and boil
one more minute. Strain through fine mesh and serve hot.
`.trim();


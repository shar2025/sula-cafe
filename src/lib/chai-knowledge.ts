export const CHAI_HISTORY = `
**How chai came to be**
Chai did not start as the spiced milky brew we know now. It grew over thousands
of years.
  - Ancient Ayurveda, around 3000 BC: long before tea, India brewed kadha, a
    medicinal infusion of spices like cardamom, ginger and clove. The flavour
    base of modern chai was already there.
  - 1830s: the British East India Company planted tea in Assam to break China's
    monopoly. Tea was grown for export, most Indians could not afford it.
  - 1900s: to make tea affordable, street vendors stretched it with milk, sugar
    and the spices they already cooked with. Masala chai was born, affordable,
    warming, unmistakably Indian.
  - Today: from train platforms to street corners to our cafe in East
    Vancouver, chai is a daily ritual. A cup, a pause, a moment to breathe.
`.trim();

